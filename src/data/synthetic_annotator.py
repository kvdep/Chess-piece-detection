"""Converts procedural Blender targets.csv annotations into YOLO txt format and splits dataset."""

import argparse
import os
import random
import shutil
from typing import Dict, List, Optional
import numpy as np
import pandas as pd

from src.constants import (
    CLASS_NAMES,
    LABEL_TO_ID,
    SYNTHETIC_BB_HEIGHT_PX,
    SYNTHETIC_BB_WIDTH_PX,
    SYNTHETIC_CELL_SIZE_PX,
    SYNTHETIC_IMG_SIZE,
    SYNTHETIC_OFFSET_PX,
)
from src.utils.box_conversions import board_cell_to_yolo_bbox


def convert_synthetic_targets_to_yolo(
    csv_path: str,
    images_source_dir: str,
    output_dataset_dir: str,
    val_percent: float = 0.1,
    random_seed: int = 42,
    copy_images: bool = True,
) -> Dict[str, int]:
    """Parse targets.csv, calculate bounding boxes, split train/test, and generate annotations.

    Args:
        csv_path: Path to targets.csv generated by blender_generator.py.
        images_source_dir: Directory containing rendered PNG images.
        output_dataset_dir: Destination root for datasets/ (images/train, labels/train, etc.).
        val_percent: Fraction of images allocated to validation/test split.
        random_seed: Random seed for reproducible dataset splitting.
        copy_images: If True, copies images; if False, only writes txt labels.

    Returns:
        Dict with image counts per split.
    """
    random.seed(random_seed)
    np.random.seed(random_seed)

    df = pd.read_csv(
        csv_path,
        header=None,
        names=["file", "label", "x", "y", "angle"],
        skiprows=1,
    )
    df["x"] = df["x"].astype(int)
    df["y"] = df["y"].astype(int)

    # Prepare directory layout
    for split in ["train", "test"]:
        os.makedirs(os.path.join(output_dataset_dir, "images", split), exist_ok=True)
        os.makedirs(os.path.join(output_dataset_dir, "labels", split), exist_ok=True)

    # Class mappings
    unique_labels = sorted(df["label"].unique())
    classes_file = os.path.join(output_dataset_dir, "classes.txt")
    with open(classes_file, "w", encoding="utf-8") as f:
        for lbl in unique_labels:
            f.write(f"{lbl}\n")

    # Group by image file ID
    all_image_ids = sorted(df["file"].unique())
    shuffled_ids = list(all_image_ids)
    random.shuffle(shuffled_ids)

    split_idx = int(len(shuffled_ids) * (1.0 - val_percent))
    train_ids = set(shuffled_ids[:split_idx])
    test_ids = set(shuffled_ids[split_idx:])

    grouped = df.groupby("file")
    stats = {"train": 0, "test": 0, "total_instances": len(df)}

    for file_id, group in grouped:
        split = "train" if file_id in train_ids else "test"
        stats[split] += 1

        annotation_lines: List[str] = []
        for _, row in group.iterrows():
            lbl_name = str(row["label"])
            cls_id = LABEL_TO_ID.get(lbl_name)
            if cls_id is None:
                continue

            cx_yolo, cy_yolo, w_yolo, h_yolo = board_cell_to_yolo_bbox(
                cell_x=row["x"],
                cell_y=row["y"],
                img_size=SYNTHETIC_IMG_SIZE,
                offset=SYNTHETIC_OFFSET_PX,
                cell_size=SYNTHETIC_CELL_SIZE_PX,
                bb_w=SYNTHETIC_BB_WIDTH_PX,
                bb_h=SYNTHETIC_BB_HEIGHT_PX,
            )

            annotation_lines.append(
                f"{cls_id} {cx_yolo:.6f} {cy_yolo:.6f} {w_yolo:.6f} {h_yolo:.6f}"
            )

        # Write YOLO label txt
        label_out_path = os.path.join(
            output_dataset_dir, "labels", split, f"{file_id}.txt"
        )
        with open(label_out_path, "w", encoding="utf-8") as lf:
            lf.write("\n".join(annotation_lines) + "\n")

        # Copy image if requested
        if copy_images:
            src_img_path = os.path.join(images_source_dir, f"{file_id}.png")
            dst_img_path = os.path.join(
                output_dataset_dir, "images", split, f"{file_id}.png"
            )
            if os.path.exists(src_img_path):
                shutil.copy2(src_img_path, dst_img_path)

    return stats


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Convert Blender targets.csv to YOLO dataset format")
    parser.add_argument("--csv_path", type=str, required=True, help="Path to targets.csv")
    parser.add_argument("--images_dir", type=str, required=True, help="Source images directory")
    parser.add_argument("--output_dir", type=str, required=True, help="Destination dataset directory")
    parser.add_argument("--val_percent", type=float, default=0.1, help="Validation split fraction")
    parser.add_argument("--no_copy_images", action="store_true", help="Do not copy images, only generate labels")
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    summary = convert_synthetic_targets_to_yolo(
        csv_path=args.csv_path,
        images_source_dir=args.images_dir,
        output_dataset_dir=args.output_dir,
        val_percent=args.val_percent,
        copy_images=not args.no_copy_images,
    )
    print(f"Dataset conversion completed: {summary}")
